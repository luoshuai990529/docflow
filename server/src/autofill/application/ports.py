"""Narrow contracts at application-to-adapter boundaries."""

from dataclasses import dataclass, field
from pathlib import Path
from typing import Protocol, runtime_checkable
from ..workflow.contracts import WorkflowProgress


@dataclass
class LLMResponse:
    data: dict
    request_id: str | None = None
    metadata: dict = field(default_factory=dict)


class LLMFailure(ValueError):
    """A model response failed a bounded transport or data contract."""

    def __init__(self, code, diagnostics):
        super().__init__(code)
        self.diagnostics = diagnostics


@runtime_checkable
class ModelClient(Protocol):
    def generate_json(self, prompt: str, schema: dict) -> LLMResponse: ...


@runtime_checkable
class DecisionClient(Protocol):
    def evaluate(self, state: dict, questions: list[dict]) -> LLMResponse: ...


@runtime_checkable
class WorkflowStateStore(Protocol):
    """State and profile operations used by workflow use cases."""

    def profiles(self) -> list[dict]: ...
    def resolve_profile_for_use(self, profile_id: str) -> tuple[object, str, dict]: ...
    def run(self, identity: str, internal: bool = False) -> dict | None: ...
    def runs(self) -> list[dict]: ...
    def by_request(self, request_id: str) -> dict | None: ...
    def create_run(self, identity: str, request_id: str, metadata: dict) -> dict: ...
    def progress(self, identity: str, stage: str, **details) -> None: ...

    def record_workflow_progress(self, identity: str, event: WorkflowProgress) -> None: ...
    def set_review(self, identity: str, review) -> None: ...
    def request_cancel(self, identity: str) -> None: ...
    def finish(self, identity: str, result: dict, node_status: str = 'success') -> None: ...
    def import_legacy(self, root) -> None: ...
    def close(self) -> None: ...


@runtime_checkable
class ProcessorPort(Protocol):
    """Fixed document conversion and OCR operations provided by the sandbox."""

    def run(self, path, operation, destination, format=None): ...
    def convert(self, path, format, destination): ...
    def ocr(self, path, destination): ...


@runtime_checkable
class DocumentPreflight(Protocol):
    @property
    def max_upload_bytes(self) -> int: ...
    def inspect_file(self, path, role: str = 'source') -> dict: ...
    def inspect_sources(self, paths: list[Path]) -> list[dict]: ...
    def digest(self, path) -> str: ...


class QuestionnaireResolver(Protocol):
    def __call__(self, path, work, processor=None) -> tuple[Path, Path, str]: ...


@runtime_checkable
class QuestionnaireStructure(Protocol):
    @property
    def max_questions(self) -> int: ...
    def enrich_source(self, document, path): ...
    def slot_anchors(self, document, path) -> dict[str, set[str]]: ...
